"""Generate docs/API_REFERENCE.md from the routes the backend actually registers.

Builds the full pilot app (core + pilot extensions) on a temporary SQLite store,
so no database or model is needed:

    backend\\.venv\\Scripts\\python.exe -X utf8 -B tools/gen_api_reference.py

Re-run after adding or changing routes; CI can diff the output.
"""
from collections import defaultdict
from pathlib import Path
import os
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
os.environ.setdefault('AEGIS_STORAGE_BACKEND', 'sqlite')

PUBLIC = {'/health', '/demo-info', '/api/auth/login', '/api/auth/register'}
# Contract documents per path prefix (most specific first).
DOCS = [
    ('/api/admin', 'backend/docs/JWT_RBAC.md'),
    ('/api/auth', 'backend/docs/API.md, backend/docs/JWT_RBAC.md'),
    ('/api/disease', 'backend/docs/API.md'),
    ('/api/farm/environment-streams', 'backend/docs/HOURLY_SOURCE_API.md, frontend/ENVIRONMENT_INGEST.md'),
    ('/api/farm/forecast', 'backend/docs/STORED_HOURLY_FORECAST_API.md, FORECAST_*_T1x.md'),
    ('/api/farm/automation', 'frontend/MOCK_AUTOMATION.md'),
    ('/api/farm/warning-episodes', 'frontend/WARNING_EPISODES.md'),
    ('/api/farm/assessment-versions', 'frontend/ASSESSMENT_VERSIONS.md'),
    ('/api/farm/follow-ups', 'backend/docs/MOBILE_FOLLOWUP_API.md'),
    ('/api/farm', 'backend/docs/FARM_WARNING_API.md, backend/docs/CULTIVATION_PROFILE.md'),
]


def doc_for(path):
    for prefix, doc in DOCS:
        if path.startswith(prefix):
            return doc
    return ''


def group_of(path):
    parts = path.strip('/').split('/')
    if parts[0] != 'api':
        return 'Service'
    if parts[1] == 'farm' and len(parts) > 2:
        seg = parts[2]
        if seg.startswith(('<', 'seasons', 'plots')):
            return 'Farm: fields, seasons and season workflows'
        if seg.startswith('forecast'):
            return 'Farm: forecasts and alerts'
        return 'Farm: ' + seg.replace('-', ' ')
    return parts[1].capitalize()


def main():
    from pilot_app import create_pilot_app
    store = Path(tempfile.mkdtemp(prefix='aegis_ui_'))
    app = create_pilot_app(store, storage_backend='sqlite',
                           config=dict(TESTING=True, UPLOAD_DIR=store / 'uploads'))
    groups = defaultdict(list)
    for rule in app.url_map.iter_rules():
        if rule.endpoint == 'static':
            continue
        methods = ', '.join(sorted(m for m in rule.methods if m not in ('HEAD', 'OPTIONS')))
        path = rule.rule.replace('<uuid:', '{').replace('<int:', '{').replace('<', '{').replace('>', '}')
        view = app.view_functions[rule.endpoint]
        auth = 'public' if rule.rule in PUBLIC else ('admin' if rule.rule.startswith('/api/admin') else 'Bearer JWT')
        groups[group_of(rule.rule)].append((path, methods, auth, view.__module__, doc_for(rule.rule)))
    total = sum(len(v) for v in groups.values())
    out = ['# API reference — generated', '',
           f'Generated by `tools/gen_api_reference.py` from the routes registered by the backend '
           f'(core + pilot extensions): **{total} routes**. Do not edit by hand; re-run the script.', '',
           'Base URL in development: `http://127.0.0.1:5000`. All `/api` endpoints exchange JSON '
           '(multipart for image upload). "Bearer JWT" means `Authorization: Bearer <access_token>` from '
           '`POST /api/auth/login`; "admin" additionally requires the admin role, checked on every request. '
           'Request/response fields, errors and examples are in the contract document listed for each route.', '']
    for name in sorted(groups, key=lambda g: (g != 'Service', g)):
        rows = sorted(groups[name])
        out += [f'## {name} ({len(rows)})', '', '| Method | Path | Auth | Module | Contract |', '|---|---|---|---|---|']
        out += [f'| {m} | `{p}` | {a} | `{mod}` | {doc} |' for p, m, a, mod, doc in rows]
        out.append('')
    target = ROOT / 'docs' / 'API_REFERENCE.md'
    target.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'{target.relative_to(ROOT)}: {total} routes in {len(groups)} groups')


if __name__ == '__main__':
    main()
