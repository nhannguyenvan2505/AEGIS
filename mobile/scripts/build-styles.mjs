import * as sass from 'sass';
import transform from 'css-to-react-native';
import { mkdirSync, writeFileSync } from 'node:fs';
const css = sass.compile('src/styles/app.scss').css;
const styles = {};
for (const match of css.matchAll(/\.([\w]+)\s*\{([^}]+)\}/g)) {
  const declarations = match[2].split(';').map(x => x.trim()).filter(Boolean).map(x => { const i = x.indexOf(':'); return [x.slice(0, i).trim(), x.slice(i + 1).trim()]; });
  styles[match[1]] = (transform.default ?? transform)(declarations);
}
mkdirSync('src/styles/generated', { recursive: true });
writeFileSync('src/styles/generated/styles.ts', '// Generated by npm run styles. Edit app.scss.\nimport { StyleSheet } from "react-native";\nexport const s = StyleSheet.create(' + JSON.stringify(styles, null, 2) + ');\n');
